#!/usr/bin/env python3
"""
Exports the trained pointwise MLP (MLPNet in models_torch.py) from a
train_all_models.py joblib bundle into a plain C header of static const
arrays, so the firmware (a real flight-controller-style C shared object,
see firmware/ge_ff.c) can run the exact same forward pass with zero
runtime dependency on Python/PyTorch/sklearn.

The MLP is the only model exported here (not Random Forest/Gradient
Boosting/LSTM/Transformer) because it is the only one that ports to a few
lines of C: a fixed-size feedforward pass (normalize -> linear -> ReLU ->
linear -> ReLU -> linear) with no recurrent state and no tree structures
to serialize. It scored essentially as well as the ensemble/sequence
models on the full 300-seed dataset (see docs/research_report.md Section
5.2b) -- Random Forest/LSTM edge it out slightly, but not enough to
justify hand-porting a tree ensemble or an LSTM's recurrent state
management into C for this project.

Usage:
    python3 ml/export_mlp_to_c.py \
        --joblib ml/results/full_dataset_lead100ms_gpu300seeds/all_models.joblib \
        --out firmware/ge_ff_ml_weights.h
"""
import argparse
import functools
from pathlib import Path

import joblib
import numpy as np
import torch


def _c_array_1d(name: str, values: np.ndarray) -> str:
    body = ", ".join(f"{v:.10g}" for v in values.tolist())
    return f"static const double {name}[{len(values)}] = {{{body}}};"


def _c_array_2d(name: str, values: np.ndarray) -> str:
    rows, cols = values.shape
    row_strs = [
        "    {" + ", ".join(f"{v:.10g}" for v in row.tolist()) + "}"
        for row in values
    ]
    body = ",\n".join(row_strs)
    return f"static const double {name}[{rows}][{cols}] = {{\n{body}\n}};"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--joblib", default="ml/results/full_dataset_lead100ms_gpu300seeds/all_models.joblib")
    ap.add_argument("--out", default="firmware/ge_ff_ml_weights.h")
    ap.add_argument("--bias-correction", type=float, default=0.0,
                     help="constant added to the raw network output before clamping -- see "
                          "docs/research_report.md Section 5.10: the offline train/test-split "
                          "bias underestimates the bias actually seen on realistic closed-loop "
                          "trajectories, so measure this separately (e.g. by scoring the model "
                          "against Cheeseman-FF-flown telemetry) rather than trusting the "
                          "in-distribution test split's own residual mean.")
    args = ap.parse_args()

    # The joblib may have been saved on a CUDA machine (see docs/research_report.md
    # Section 5.2b) -- force every tensor back to CPU regardless of what GPUs
    # exist here.
    orig_torch_load = torch.load
    torch.load = functools.partial(orig_torch_load, map_location="cpu")
    bundle = joblib.load(args.joblib)
    torch.load = orig_torch_load

    features = bundle["features"]
    state = bundle["mlp_model_state"]
    scaler = bundle["mlp_scaler"]

    w0 = state["net.0.weight"].numpy()  # [64, 13]
    b0 = state["net.0.bias"].numpy()    # [64]
    w1 = state["net.2.weight"].numpy()  # [32, 64]
    b1 = state["net.2.bias"].numpy()    # [32]
    w2 = state["net.4.weight"].numpy()  # [1, 32]
    b2 = state["net.4.bias"].numpy()    # [1]

    n_features, h1, h2 = w0.shape[1], w0.shape[0], w1.shape[0]
    assert h2 == w2.shape[1] and w2.shape[0] == 1

    lines = [
        "#ifndef GE_FF_ML_WEIGHTS_H",
        "#define GE_FF_ML_WEIGHTS_H",
        "",
        "/* Auto-generated by ml/export_mlp_to_c.py from",
        f" * {args.joblib} -- do not hand-edit, regenerate after retraining.",
        " *",
        " * Feature order (must match the sensor_packet_t fields packed in",
        " * firmware/ge_ff.c's caller, in exactly this order):",
        " *   " + ", ".join(features),
        " */",
        "",
        f"#define GE_FF_ML_N_FEATURES {n_features}",
        f"#define GE_FF_ML_H1 {h1}",
        f"#define GE_FF_ML_H2 {h2}",
        f"#define GE_FF_ML_BIAS_CORRECTION {args.bias_correction:.10g} /* added to raw output, see --bias-correction help */",
        "",
        "/* StandardScaler applied to the raw features before the first layer. */",
        _c_array_1d("GE_FF_ML_SCALER_MEAN", scaler.mean_),
        _c_array_1d("GE_FF_ML_SCALER_SCALE", scaler.scale_),
        "",
        "/* net.0: Linear(N_FEATURES -> H1), followed by ReLU. */",
        _c_array_2d("GE_FF_ML_W0", w0),
        _c_array_1d("GE_FF_ML_B0", b0),
        "",
        "/* net.2: Linear(H1 -> H2), followed by ReLU. */",
        _c_array_2d("GE_FF_ML_W1", w1),
        _c_array_1d("GE_FF_ML_B1", b1),
        "",
        "/* net.4: Linear(H2 -> 1), no activation (raw regression output). */",
        _c_array_2d("GE_FF_ML_W2", w2),
        _c_array_1d("GE_FF_ML_B2", b2),
        "",
        "#endif",
        "",
    ]

    out_path = Path(args.out)
    out_path.write_text("\n".join(lines))
    print(f"[export] wrote {out_path} ({n_features} features, {h1}/{h2} hidden units)")


if __name__ == "__main__":
    main()
